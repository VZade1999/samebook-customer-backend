import { Injectable } from '@nestjs/common';
import { createHash, randomUUID } from 'crypto';
import { createReadStream, promises as fs, ReadStream } from 'fs';
import * as path from 'path';

/**
 * Where Drive keeps the bytes. Blobs are immutable: a new version is a new
 * blob, nothing is ever overwritten or deleted, so a version's storage_key
 * stays valid forever. Swap this class for an S3 implementation later — the
 * service only uses put()/open()/exists().
 */
export interface StoredBlob {
  key: string;
  size: number;
  sha256: string;
}

const DEFAULT_ROOT = path.resolve(process.cwd(), 'storage', 'drive');

@Injectable()
export class DriveStorage {
  /** Read lazily so DRIVE_STORAGE_DIR from .env.local is honoured. */
  get root(): string {
    return path.resolve(process.env.DRIVE_STORAGE_DIR || DEFAULT_ROOT);
  }

  /** Multer writes uploads here first; put() moves them into place. */
  get tmpDir(): string {
    return path.join(this.root, '_incoming');
  }

  async ensureDirs() {
    await fs.mkdir(this.tmpDir, { recursive: true });
  }

  private resolveKey(key: string): string {
    const full = path.resolve(this.root, key);
    // Keys are generated by us, but never let one escape the root.
    if (!full.startsWith(this.root + path.sep)) throw new Error('Invalid storage key');
    return full;
  }

  private hashFile(file: string): Promise<{ sha256: string; size: number }> {
    return new Promise((resolve, reject) => {
      const hash = createHash('sha256');
      let size = 0;
      createReadStream(file)
        .on('data', (chunk: Buffer) => {
          size += chunk.length;
          hash.update(chunk);
        })
        .on('error', reject)
        .on('end', () => resolve({ sha256: hash.digest('hex'), size }));
    });
  }

  /** Moves an uploaded temp file into permanent, company-scoped storage. */
  async put(companyId: number, tmpPath: string, ext: string): Promise<StoredBlob> {
    const { sha256, size } = await this.hashFile(tmpPath);
    const d = new Date();
    const key = [
      `c${Number(companyId)}`,
      String(d.getFullYear()),
      String(d.getMonth() + 1).padStart(2, '0'),
      `${randomUUID()}${ext ? `.${ext}` : ''}`,
    ].join('/');
    const dest = this.resolveKey(key);
    await fs.mkdir(path.dirname(dest), { recursive: true });
    try {
      await fs.rename(tmpPath, dest);
    } catch {
      // Different volume: copy then remove the temp file.
      await fs.copyFile(tmpPath, dest);
      await fs.unlink(tmpPath).catch(() => undefined);
    }
    return { key, size, sha256 };
  }

  async exists(key: string): Promise<boolean> {
    try {
      await fs.access(this.resolveKey(key));
      return true;
    } catch {
      return false;
    }
  }

  open(key: string): ReadStream {
    return createReadStream(this.resolveKey(key));
  }

  /** Best-effort cleanup of a temp upload that was rejected. */
  async discardTemp(tmpPath?: string) {
    if (tmpPath && path.resolve(tmpPath).startsWith(this.tmpDir + path.sep)) {
      await fs.unlink(tmpPath).catch(() => undefined);
    }
  }
}

/** One shared instance: multer's disk storage (decorator time) and DI use the same. */
export const driveStorage = new DriveStorage();
